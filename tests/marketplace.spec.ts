test('timeout após criar pedido recupera a compra sem duplicar', async ({ page }) => {
  await page.goto('/nft/042')
  await page.getByRole('button', { name: 'Adicionar ao carrinho' }).click()
  await page.goto('/login')
  await page.getByLabel('E-mail').fill('ana@kurio.test')
  await page.getByLabel('Senha').fill('kurio1234')
  await page.getByRole('button', { name: 'Entrar' }).last().click()
  await page.evaluate(() => localStorage.setItem('kurio-scenario', 'order-timeout'))
  await page.goto('/checkout')
  await page.getByRole('radio').first().check()
  await page.getByRole('button', { name: 'Confirmar compra' }).click()
  await expect(page.getByRole('heading', { name: 'Seus NFTs agora estão na sua carteira' })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Total: 1.206 ETH')).toBeVisible()
  const count = await page.evaluate(async () => (await (await fetch('/api/orders', { headers: { Authorization: `Bearer ${localStorage.getItem('kurio-token')}` } })).json()).length)
  expect(count).toBe(1)
})

